<?php

declare(strict_types=1);

namespace DDD\Presentation\Api\Admin\DesignStudio\Traits;

use DDD\Domain\DesignStudio\Entities\Thumbnails\DesignStudioThumbnail;
use DDD\Domain\DesignStudio\Services\DesignBoardAssetsService;
use DDD\Domain\DesignStudio\Services\DesignBoardContentService;
use DDD\Domain\DesignStudio\Services\DesignStudioCanvasViewsService;
use DDD\Domain\DesignStudio\Services\DesignStudioThumbnailsService;
use DDD\Domain\DesignStudio\Services\DesignThemeProviderService;
use DDD\Presentation\Api\Admin\DesignStudio\Dtos\DesignStudioAssetContentGetRequestDto;
use DDD\Presentation\Api\Admin\DesignStudio\Dtos\DesignStudioBoardContentGetRequestDto;
use DDD\Presentation\Api\Admin\DesignStudio\Dtos\DesignStudioThumbnailContentGetRequestDto;
use DDD\Infrastructure\Exceptions\BadRequestException;
use DDD\Infrastructure\Exceptions\InternalErrorException;
use DDD\Infrastructure\Exceptions\NotFoundException;
use DDD\Presentation\Base\Dtos\HtmlResponseDto;
use DDD\Presentation\Base\Dtos\ImageResponseDto;
use DDD\Presentation\Base\Router\Routes\Get;
use DDD\Presentation\Services\RequestService;
use Psr\Cache\InvalidArgumentException;
use ReflectionException;

/**
 * Delivers board files and thumbnails to `<iframe src>` / `<img src>`. These requests carry no Authorization header:
 * the application lets the routes through its firewall, and access comes only from the content token in the URL
 * (DesignBoardContentService). Board files are generated by agents, so the HTML answer carries a strict CSP: no
 * scripts, no network except the Google Fonts stylesheet, images only as data URIs or from this application (the
 * canvas' asset files, DesignBoardAssetsService), no forms, framing only by the application itself, and the CSP
 * `sandbox` directive (an opaque origin even when the URL is opened directly). The
 * studio page embeds it in an `<iframe sandbox="">` on top. An application uses the trait in a controller of its own,
 * mounted at the path of the config `DesignStudio.api.contentBasePath` and hidden from the API documentation.
 */
trait DesignStudioContentControllerTrait
{
    /**
     * The board file for the sandboxed iframe, with `theme` in that look.
     * @param DesignStudioBoardContentGetRequestDto $requestDto
     * @param DesignBoardContentService $designBoardContentService
     * @param DesignStudioCanvasViewsService $designStudioCanvasViewsService
     * @param DesignThemeProviderService $designThemeProviderService
     * @return HtmlResponseDto
     * @throws BadRequestException
     * @throws InternalErrorException
     * @throws NotFoundException
     */
    #[Get('/boards/{projectKey}/{canvasKey}/{boardKey}', requirements: ['boardKey' => '[^/]+'])]
    public function getBoardHtml(
        DesignStudioBoardContentGetRequestDto $requestDto,
        DesignBoardContentService $designBoardContentService,
        DesignStudioCanvasViewsService $designStudioCanvasViewsService,
        DesignThemeProviderService $designThemeProviderService,
        DesignBoardAssetsService $designBoardAssetsService,
        RequestService $requestService
    ): HtmlResponseDto {
        $designBoardContentService->authenticateContentToken($requestDto->token);
        $canvasDefinition = $designStudioCanvasViewsService->getCanvasDefinition($requestDto->projectKey, $requestDto->canvasKey);
        $themeStyle = $designThemeProviderService->getThemeStyleForReference($requestDto->theme);
        $boardHtml = $designBoardContentService->getBoardHtmlForSandbox($canvasDefinition, $requestDto->boardKey, $requestDto->contentHash, $themeStyle);
        if ($boardHtml === null) {
            throw new NotFoundException('Design content not found');
        }
        // asset references (`assets/…`) point at the asset route, with the token and the version this board version shows
        $designBoardAssetReferences = $designBoardAssetsService->findAssetReferencesForBoardVersion(
            $canvasDefinition,
            $requestDto->boardKey,
            $requestDto->contentHash,
            $boardHtml
        );
        if ($designBoardAssetReferences->count()) {
            $boardHtml = $designBoardAssetsService->rewriteAssetReferencesToContentRoute(
                $boardHtml,
                $designBoardAssetReferences,
                $designStudioCanvasViewsService->getContentBasePath() . '/assets/' . rawurlencode($requestDto->projectKey)
                . '/' . rawurlencode($requestDto->canvasKey),
                'token=' . rawurlencode((string)$requestDto->token)
            );
        }
        $response = new HtmlResponseDto($boardHtml, 200, [], 'text/html; charset=utf-8');
        $response->headers->set(
            'Content-Security-Policy',
            implode('; ', $this->getBoardHtmlContentSecurityPolicyDirectives($requestService->getRequestStack()->getCurrentRequest()?->getSchemeAndHttpHost()))
        );
        // a URL with a content hash names one version for good (with asset files: only together with their version);
        // without one it follows the checkout
        $isImmutable = $requestDto->contentHash !== null
            && (!$designBoardAssetReferences->count() || $requestDto->assetsHash === $designBoardAssetReferences->computeAssetsHash());
        $this->setDesignStudioContentHeaders($response, sha1($boardHtml), $isImmutable);
        return $response;
    }

    /**
     * An asset file of the canvas' `assets/` folder (an image a board references), in the version `v` names: the
     * checkout's file, or the file kept with a commented board version.
     * @param DesignStudioAssetContentGetRequestDto $requestDto
     * @param DesignBoardContentService $designBoardContentService
     * @param DesignStudioCanvasViewsService $designStudioCanvasViewsService
     * @param DesignBoardAssetsService $designBoardAssetsService
     * @return ImageResponseDto
     * @throws BadRequestException
     * @throws InternalErrorException
     * @throws NotFoundException
     */
    #[Get('/assets/{projectKey}/{canvasKey}/{assetPath}', requirements: ['assetPath' => '.+'])]
    public function getAsset(
        DesignStudioAssetContentGetRequestDto $requestDto,
        DesignBoardContentService $designBoardContentService,
        DesignStudioCanvasViewsService $designStudioCanvasViewsService,
        DesignBoardAssetsService $designBoardAssetsService
    ): ImageResponseDto {
        $designBoardContentService->authenticateContentToken($requestDto->token);
        $canvasDefinition = $designStudioCanvasViewsService->getCanvasDefinition($requestDto->projectKey, $requestDto->canvasKey);
        $designBoardAsset = $designBoardAssetsService->readAsset($canvasDefinition, $requestDto->assetPath, $requestDto->v);
        if ($designBoardAsset === null) {
            throw new NotFoundException('Design content not found');
        }
        $response = new ImageResponseDto($designBoardAsset->content, 200, [], (string)$designBoardAsset->mediaType);
        // an SVG opened directly runs nothing and loads nothing
        $response->headers->set('Content-Security-Policy', "default-src 'none'; style-src 'unsafe-inline'; img-src data:; sandbox");
        $this->setDesignStudioContentHeaders($response, (string)$designBoardAsset->contentHash, $requestDto->v !== null);
        // loaded by the board's sandboxed iframe, whose origin is opaque: same-origin would block it
        $response->headers->set('Cross-Origin-Resource-Policy', 'cross-origin');
        return $response;
    }

    /**
     * A rendered thumbnail (size=small: the reduced copy for far zoom levels; size=preview: the canvas copy, WebP or
     * JPEG).
     * @param DesignStudioThumbnailContentGetRequestDto $requestDto
     * @param DesignBoardContentService $designBoardContentService
     * @param DesignStudioThumbnailsService $designStudioThumbnailsService
     * @return ImageResponseDto
     * @throws BadRequestException
     * @throws InternalErrorException
     * @throws InvalidArgumentException
     * @throws NotFoundException
     * @throws ReflectionException
     */
    #[Get('/thumbnails/{thumbnailKey}', requirements: ['thumbnailKey' => '[0-9a-f]{64}'])]
    public function getThumbnail(
        DesignStudioThumbnailContentGetRequestDto $requestDto,
        DesignBoardContentService $designBoardContentService,
        DesignStudioThumbnailsService $designStudioThumbnailsService
    ): ImageResponseDto {
        $designBoardContentService->authenticateContentToken($requestDto->token);
        $image = $designStudioThumbnailsService->getThumbnailContent($requestDto->thumbnailKey, $requestDto->size ?? DesignStudioThumbnail::SIZE_FULL);
        if ($image === null) {
            throw new NotFoundException('Design content not found');
        }
        $mediaType = (getimagesizefromstring($image) ?: [])['mime'] ?? 'image/png';
        $response = new ImageResponseDto($image, 200, [], in_array($mediaType, ['image/png', 'image/webp', 'image/jpeg'], true) ? $mediaType : 'image/png');
        $response->headers->set('Content-Security-Policy', "default-src 'none'; sandbox");
        $this->setDesignStudioContentHeaders($response, sha1($image), true);
        return $response;
    }

    /**
     * @param string|null $applicationOrigin scheme and host of the application (`https://admin.example.com`): the
     *        origin of the asset route. Named explicitly because `'self'` of a sandboxed document is not reliably its
     *        URL's origin.
     * @return string[] Content-Security-Policy directives of board HTML
     */
    protected function getBoardHtmlContentSecurityPolicyDirectives(?string $applicationOrigin = null): array
    {
        return [
            "default-src 'none'",
            "style-src 'unsafe-inline' https://fonts.googleapis.com",
            'font-src https://fonts.gstatic.com data:',
            trim("img-src data: blob: 'self' " . ($applicationOrigin ?? '')),
            "script-src 'none'",
            "connect-src 'none'",
            "form-action 'none'",
            "base-uri 'none'",
            "frame-ancestors 'self'",
            'sandbox',
        ];
    }

    /**
     * @param HtmlResponseDto|ImageResponseDto $response
     * @param string $entityTag hash of the delivered bytes
     * @param bool $isImmutable true: the URL names content that never changes (kept by the browser for a year;
     *        `private`: only the viewer's own browser keeps the copy, which the token in the URL already gave it)
     * @return void
     */
    protected function setDesignStudioContentHeaders(HtmlResponseDto|ImageResponseDto $response, string $entityTag, bool $isImmutable): void
    {
        $response->headers->set('X-Content-Type-Options', 'nosniff');
        $response->headers->set('Referrer-Policy', 'no-referrer');
        $response->headers->set('Cross-Origin-Resource-Policy', 'same-origin');
        $response->headers->set('Cache-Control', $isImmutable ? 'private, max-age=31536000, immutable' : 'private, no-cache');
        $response->setEtag($entityTag);
        $response->headers->remove('Pragma');
    }
}
